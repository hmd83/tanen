#!/usr/bin/env python3
"""
Golden vectors for test_tempcomp.c, generated by the Python reference.

The oracle is firmware_replay() from docs/load_cells/SBS-PF-150/analysis/ —
the documented bit-exact Python copy of tempcomp.c that the load-cell reports
quote their "firmware replay" sigma from. The host test replays the same rows
through the real src/ code and must match every row exactly, so the C and the
Python reference cannot drift apart silently: change one, regenerate, and the
diff shows up in review.

Only needed when the filter or a dataset changes, not to run the tests — the
output is committed and CI needs no Python stack.

    pip install pandas numpy matplotlib
    python3 tests/host/gen_golden.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LC = os.path.join(HERE, "..", "..", "docs", "load_cells")
sys.path.insert(0, os.path.join(LC, "SBS-PF-150", "analysis"))
import tempcomp_analysis as ref  # noqa: E402  (SBS script, has firmware_replay)

import numpy as np   # noqa: E402
import pandas as pd  # noqa: E402

OUT = os.path.join(HERE, "golden")
T_REF_MDEG = int(ref.T_REF_C * 1000)
TAU_S = int(ref.TAU_MIN * 60)

# Profile gains from src/config/config.c lc_profiles[]. Kept as literals, not
# parsed out of the C: a golden file that silently followed a typo in the table
# would test nothing.
H40A_GAIN = 17734
SBS_GAIN = 10681


def load(path):
    df = pd.read_csv(path, sep=";", quotechar='"')
    df.columns = ["time", "T", "W"]
    df["time"] = pd.to_datetime(df["time"])
    df = df.dropna().reset_index(drop=True)
    df["dt"] = df.time.diff().dt.total_seconds().fillna(0.0)
    return df


def write(name, note, df, dt_s, gain):
    comp = ref.firmware_replay(df["T"].values, df.W.values, dt_s,
                               gain, TAU_S, T_REF_MDEG)
    raw_g = df.W.values.std() * 1000
    comp_g = comp.std() * 1000
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".csv"), "w", newline="\n") as f:
        f.write(f"# {note}\n")
        f.write("# generated by tests/host/gen_golden.py — do not edit\n")
        f.write(f"# gain_mg_per_k={gain} tau_s={TAU_S} t_ref_mdeg={T_REF_MDEG}\n")
        f.write(f"# sigma_raw_g={raw_g:.2f} sigma_comp_g={comp_g:.2f}\n")
        f.write("dt_s;t_mdeg;w_raw_mg;w_comp_mg\n")
        for d, t, w, c in zip(dt_s, df["T"].values, df.W.values, comp):
            f.write(f"{int(d)};{int(round(t * 1000))};"
                    f"{int(round(w * 1e6))};{int(round(c * 1e6))}\n")
    print(f"{name:12s} n={len(df):4d}  raw sigma={raw_g:6.2f} g  "
          f"comp sigma={comp_g:6.2f} g")


def main():
    h40a = load(os.path.join(LC, "H40A-C3-0150", "data", "Loadcell_B.csv"))
    write("h40a_rowdt",
          "H40A-C3-0150 reference run, Loadcell_B.csv, dt from the timestamps",
          h40a, h40a.dt.values, H40A_GAIN)
    write("h40a_300s",
          "H40A-C3-0150 reference run, Loadcell_B.csv, every wake 300 s apart "
          "(default CONFIG_TANENBASE_DEFAULT_MS_INTERVAL)",
          h40a, np.full(len(h40a), 300.0), H40A_GAIN)

    sbs = load(ref.DATA)
    sbs = sbs[(sbs.time >= ref.FIT_START) & (sbs.time < ref.FIT_END)]
    sbs = sbs.reset_index(drop=True)
    write("sbs_pf150",
          "SBS-PF-150 production week, fit window of its report, "
          "dt from the timestamps",
          sbs, sbs.dt.values, SBS_GAIN)


if __name__ == "__main__":
    main()
